/// Scored move returned by PFL3 99%-contralateral goal-vector steering + Noduli expectation.
#[derive(Copy, Clone, Debug)]
pub struct PolicyMoveScore {
    pub mv: Move,
    pub prob: f32,
    pub logit: f32,
    /// Noduli Efference-Copy expected centipawn delta upon playing this move.
    pub expected_delta_cp: f32,
}

/// Complete output of Stream B strategic deliberation (cached in StrategicTT).
#[derive(Clone, Debug)]
pub struct StreamBOutput {
    pub deep_cp: f32,
    pub wdl_probs: [f32; 3],
    /// PFL2 50/50 bilateral sharpness/urgency gain in [0, 1] (drives search extensions & LMR).
    pub pfl2_sharpness: f32,
    /// Number of Central Complex deliberation ticks actually executed (2..=T_max).
    pub ticks_used: usize,
    /// 10-20 ply Strategic Pressure forecast: [mob_collapse, entropy, king_press, space, prophylaxis].
    pub strategic_pressure: [f32; 5],
    /// K = 4 orthogonal strategic goal vectors generated by the Fan-Shaped Body.
    pub creative_plans: Vec<Vec<f32>>,
    /// Selected committed goal vector blended with MBON-a'3 novelty and LAL continuity.
    pub committed_goal: Vec<f32>,
    /// Legal moves ranked by PFL3 99%-contralateral goal-vector steering.
    pub policy_moves: Vec<PolicyMoveScore>,
    /// Top-down Stream B -> Stream A fast-weight seed for intra-search gamma lobe.
    pub gamma_seed: Vec<f32>,
    /// Top-down Stream B -> Stream A inhibitory Centrifugal mask on Kenyon Cells.
    pub centrifugal_kc_mask: Vec<f32>,
    /// 64-square top-down Visual Centrifugal attention weights (for diagnostics).
    pub centrifugal_board_mask: [f32; 64],
}

fn matvec(w: &[f32], x: &[f32], rows: usize, cols: usize, out: &mut [f32]) {
    for r in 0..rows {
        out[r] = dot_f32(&w[r * cols..(r + 1) * cols], x);
    }
}

/// Runs the complete Stream B Deep Strategic Brain on `pos` with legal moves `legal_moves`.
///
/// `mbon_summary` is the 32-dim Push-Pull MBON signal from Stream A (feeding CX Ring/Tangential).
/// `sez_cp` is the SEZ innate survival valence in centipawns fused cleanly into deep strategic value.
/// `serotonin` in [0.5, 1.5] modulates hDelta 180-deg prophylaxis weight & strategic persistence.
#[allow(clippy::too_many_arguments)]
pub fn evaluate_stream_b(
    pos: &Position,
    legal_moves: &MoveList,
    w: &SaccadionWeights,
    mbon_summary: &[f32],
    sez_cp: f32,
    plasticity: Option<&DopaminePlasticityState>,
    novelty_score: f32,
    serotonin: f32,
    adaptive_halt: bool,
) -> StreamBOutput {
    let cfg = &w.cfg;
    let d = cfg.stream_b_dim;
    let sq_in = cfg.sq_feat_dim;
    let n_int = cfg.num_integrators;
    let n_broad = cfg.num_broadcasters;
    let n_hubs = n_int + n_broad;
    let sectors = cfg.cx_sectors; // 16 chess compass vectors
    let cx_d = cfg.cx_dim;

    // -------------------------------------------------------------------------
    // B1. T4/T5 Shunting Inhibition Optic Encoder + Lobula Columnar Projection
    //     y = ReLU(E) / (softplus(g_leak) + 0.5 + ReLU(I)) + LC
    // -------------------------------------------------------------------------
    let board_feats = extract_stream_b_board(pos);
    let mut sq_state = vec![0.0f32; 64 * d];
    let mut e_buf = vec![0.0f32; d];
    let mut i_buf = vec![0.0f32; d];
    let mut lc_buf = vec![0.0f32; d];

    for sq in 0..64 {
        let x = &board_feats[sq];
        matvec(&w.b_shunt_exc, x, d, sq_in, &mut e_buf);
        matvec(&w.b_shunt_inh, x, d, sq_in, &mut i_buf);
        matvec(&w.b_lc_w, x, d, sq_in, &mut lc_buf);
        let dst = &mut sq_state[sq * d..(sq + 1) * d];
        for j in 0..d {
            let exc = e_buf[j].max(0.0);
            let inh = i_buf[j].max(0.0);
            let leak = softplus(w.b_shunt_leak[j]) + 0.5;
            dst[j] = (exc / (leak + inh)) + lc_buf[j] + w.b_optic_b[j];
        }
    }

    // -------------------------------------------------------------------------
    // B1b. 3-Layer Untied FlyWire Optic Lobe Stack (Medulla -> Lobula -> Lobula Plate):
    //      Pre-LN -> Dm/Pm 4-Head 64x64 Retinotopic Attention -> Pre-LN -> Tm/TmY SwiGLU FFN!
    //      Runs ONCE per Stream B evaluation (2x faster on CPU than 6x repeated attention,
    //      while delivering deep 3-layer hierarchical chess vision across all 64 squares!)
    // -------------------------------------------------------------------------
    let n_lob_heads = 4usize;
    let lob_hd = d / n_lob_heads;
    let inv_sqrt_hd = 1.0 / (lob_hd as f32).sqrt();
    let ffn_d = 2 * d;

    let mut lob_q = vec![0.0f32; 64 * d];
    let mut lob_k = vec![0.0f32; 64 * d];
    let mut lob_v = vec![0.0f32; 64 * d];
    let mut lob_ctx = vec![0.0f32; 64 * d];
    let mut attn_scores = [0.0f32; 64];
    let mut o_buf = vec![0.0f32; d];
    let mut sq_ln = vec![0.0f32; d];
    let mut ffn_g = vec![0.0f32; ffn_d];
    let mut ffn_u = vec![0.0f32; ffn_d];

    for l in 0..OPTIC_LAYERS {
        let ln1_g = &w.b_opt_ln1_g[l * d..(l + 1) * d];
        let ln1_b = &w.b_opt_ln1_b[l * d..(l + 1) * d];
        let wq = &w.b_opt_q[l * d * d..(l + 1) * d * d];
        let wk = &w.b_opt_k[l * d * d..(l + 1) * d * d];
        let wv = &w.b_opt_v[l * d * d..(l + 1) * d * d];
        let wo = &w.b_opt_o[l * d * d..(l + 1) * d * d];
        let wrel = &w.b_opt_rel[l * 4 * 4096..(l + 1) * 4 * 4096];

        // 1) Pre-LN + Dm/Pm 4-Head 64x64 Retinotopic Spatial Attention
        for sq in 0..64 {
            layer_norm(&sq_state[sq * d..(sq + 1) * d], ln1_g, ln1_b, &mut sq_ln);
            matvec(wq, &sq_ln, d, d, &mut lob_q[sq * d..(sq + 1) * d]);
            matvec(wk, &sq_ln, d, d, &mut lob_k[sq * d..(sq + 1) * d]);
            matvec(wv, &sq_ln, d, d, &mut lob_v[sq * d..(sq + 1) * d]);
        }
        lob_ctx.fill(0.0);
        for h in 0..n_lob_heads {
            let h_off = h * lob_hd;
            let rel_head_off = h * 4096;
            for u in 0..64 {
                let qu = &lob_q[u * d + h_off..u * d + h_off + lob_hd];
                let rel_row = &wrel[rel_head_off + u * 64..rel_head_off + (u + 1) * 64];
                for v in 0..64 {
                    let kv = &lob_k[v * d + h_off..v * d + h_off + lob_hd];
                    attn_scores[v] = dot_f32(qu, kv) * inv_sqrt_hd + rel_row[v];
                }
                softmax_inplace(&mut attn_scores);
                let dst = &mut lob_ctx[u * d + h_off..u * d + h_off + lob_hd];
                for v in 0..64 {
                    let a = attn_scores[v];
                    let vv = &lob_v[v * d + h_off..v * d + h_off + lob_hd];
                    for j in 0..lob_hd {
                        dst[j] += a * vv[j];
                    }
                }
            }
        }
        for sq in 0..64 {
            matvec(wo, &lob_ctx[sq * d..(sq + 1) * d], d, d, &mut o_buf);
            let cur = &mut sq_state[sq * d..(sq + 1) * d];
            for j in 0..d {
                cur[j] += o_buf[j];
            }
        }

        // 2) Pre-LN + Tm/TmY Columnar SwiGLU FFN (D -> 2D -> D)
        let ln2_g = &w.b_opt_ln2_g[l * d..(l + 1) * d];
        let ln2_b = &w.b_opt_ln2_b[l * d..(l + 1) * d];
        let wfg = &w.b_opt_fg[l * ffn_d * d..(l + 1) * ffn_d * d];
        let wfu = &w.b_opt_fu[l * ffn_d * d..(l + 1) * ffn_d * d];
        let wfd = &w.b_opt_fd[l * d * ffn_d..(l + 1) * d * ffn_d];

        for sq in 0..64 {
            layer_norm(&sq_state[sq * d..(sq + 1) * d], ln2_g, ln2_b, &mut sq_ln);
            matvec(wfg, &sq_ln, ffn_d, d, &mut ffn_g);
            matvec(wfu, &sq_ln, ffn_d, d, &mut ffn_u);
            for j in 0..ffn_d {
                ffn_g[j] = silu(ffn_g[j]) * ffn_u[j];
            }
            matvec(wfd, &ffn_g, d, ffn_d, &mut o_buf);
            let cur = &mut sq_state[sq * d..(sq + 1) * d];
            for j in 0..d {
                cur[j] += o_buf[j];
            }
        }
    }

    // Initialize Rich-Club hubs (Integrators [0..n_int], Broadcasters [n_int..n_hubs])
    let mut hubs = w.b_hub_init.clone();
    // Initialize 16-sector Central Complex Phasor state C^{(0)} [16, cx_d]
    let mut cx_phasor = vec![0.0f32; sectors * cx_d];
    let mut prev_phasor = vec![0.0f32; sectors * cx_d];

    // Preallocate tick scratch buffers
    let mut sq_k = vec![0.0f32; 64 * d];
    let mut sq_v = vec![0.0f32; 64 * d];
    let mut q_buf = vec![0.0f32; d];
    let mut ctx_buf = vec![0.0f32; d];
    let mut hub_tmp = vec![0.0f32; d];
    let mut hub_ln = vec![0.0f32; d];
    let mut int_mean = vec![0.0f32; d];
    let mut broad_mean = vec![0.0f32; d];
    let mut pfn_stm = vec![0.0f32; sectors * cx_d];
    let mut pfn_opp = vec![0.0f32; sectors * cx_d];
    let mut u_phasor = vec![0.0f32; sectors * cx_d];
    let mut delta7_scores = vec![0.0f32; sectors * cx_d];
    let mut ring_in = vec![0.0f32; d + cfg.mbon_dim];
    let mut ring_gate = vec![0.0f32; cx_d];
    let mut cent_board_mask = [0.5f32; 64];
    let mut broad_proj = vec![0.0f32; d];
    let mut sq_tmp = vec![0.0f32; d];

    let inv_sqrt_d = 1.0 / (d as f32).sqrt();
    let mut ticks_used = 0usize;

    // -------------------------------------------------------------------------
    // B2-B4. Weight-Tied Central Complex + Rich-Club Recurrent Deliberation Loop
    // -------------------------------------------------------------------------
    for tick in 0..cfg.cx_max_ticks {
        ticks_used = tick + 1;
        prev_phasor.copy_from_slice(&cx_phasor);

        // Step A: Integrators Cross-Attention pulling global board tension from 64 squares
        for sq in 0..64 {
            let s = &sq_state[sq * d..(sq + 1) * d];
            matvec(&w.b_int_k, s, d, d, &mut sq_k[sq * d..(sq + 1) * d]);
            matvec(&w.b_int_v, s, d, d, &mut sq_v[sq * d..(sq + 1) * d]);
        }
        for h in 0..n_int {
            let h_slice = &hubs[h * d..(h + 1) * d];
            matvec(&w.b_int_q, h_slice, d, d, &mut q_buf);
            for sq in 0..64 {
                attn_scores[sq] = dot_f32(&q_buf, &sq_k[sq * d..(sq + 1) * d]) * inv_sqrt_d;
            }
            softmax_inplace(&mut attn_scores);
            ctx_buf.fill(0.0);
            for sq in 0..64 {
                let a = attn_scores[sq];
                let vs = &sq_v[sq * d..(sq + 1) * d];
                for j in 0..d {
                    ctx_buf[j] += a * vs[j];
                }
            }
            matvec(&w.b_int_o, &ctx_buf, d, d, &mut o_buf);
            for j in 0..d {
                hub_tmp[j] = hubs[h * d + j] + o_buf[j];
            }
            layer_norm(&hub_tmp, &w.b_rc_ln_g, &w.b_rc_ln_b, &mut hub_ln);
            hubs[h * d..(h + 1) * d].copy_from_slice(&hub_ln);
        }

        // Step B: Rich-Club Core Exchange (Integrators -> Broadcasters dense 5.4x coupling)
        int_mean.fill(0.0);
        for h in 0..n_int {
            for j in 0..d {
                int_mean[j] += hubs[h * d + j] / n_int as f32;
            }
        }
        for h in 0..n_hubs {
            // Mix each hub with Rich-Club global integrator summary
            for j in 0..d {
                ctx_buf[j] = 0.5 * hubs[h * d + j] + 0.5 * int_mean[j];
            }
            matvec(&w.b_rc_mix1, &ctx_buf, d, d, &mut o_buf);
            for x in &mut o_buf {
                *x = (*x).max(0.0);
            }
            matvec(&w.b_rc_mix2, &o_buf, d, d, &mut hub_tmp);
            for j in 0..d {
                hub_tmp[j] += hubs[h * d + j];
            }
            layer_norm(&hub_tmp, &w.b_rc_ln_g, &w.b_rc_ln_b, &mut hub_ln);
            hubs[h * d..(h + 1) * d].copy_from_slice(&hub_ln);
        }

        broad_mean.fill(0.0);
        for h in n_int..n_hubs {
            for j in 0..d {
                broad_mean[j] += hubs[h * d + j] / n_broad as f32;
            }
        }

        // Step C: Central Complex Phasor Engine
        //   1) PFN (94.8% E) force projection onto 16 compass sectors (STM vs Opponent)
        for sec in 0..sectors {
            let off = sec * cx_d * d;
            matvec(
                &w.b_pfn_stm[off..off + cx_d * d],
                &int_mean,
                cx_d,
                d,
                &mut pfn_stm[sec * cx_d..(sec + 1) * cx_d],
            );
            matvec(
                &w.b_pfn_opp[off..off + cx_d * d],
                &broad_mean,
                cx_d,
                d,
                &mut pfn_opp[sec * cx_d..(sec + 1) * cx_d],
            );
        }

        //   2) vDelta multi-step plan composition + hDelta 180-deg phase shift (roll by 8 sectors!)
        //      modulated by Serotonin (Prophylaxis = subtract opponent counter-plan vector)
        let mut v_tmp = vec![0.0f32; cx_d];
        let mut h_tmp = vec![0.0f32; cx_d];
        for sec in 0..sectors {
            let prev_s = &cx_phasor[sec * cx_d..(sec + 1) * cx_d];
            matvec(&w.b_vdelta, prev_s, cx_d, cx_d, &mut v_tmp);
            let opp_sec = (sec + sectors / 2) % sectors; // Exact 180-degree ring shift!
            let opp_s = &pfn_opp[opp_sec * cx_d..(opp_sec + 1) * cx_d];
            matvec(&w.b_hdelta, opp_s, cx_d, cx_d, &mut h_tmp);
            for j in 0..cx_d {
                u_phasor[sec * cx_d + j] =
                    pfn_stm[sec * cx_d + j] + v_tmp[j] - serotonin * h_tmp[j];
            }
        }

        //   3) Delta7 (97.6% I) unimodal ring sharpening + CX Ring/Tangential (91-99.6% I) carving
        ring_in[..d].copy_from_slice(&int_mean);
        let m_copy = cfg.mbon_dim.min(mbon_summary.len());
        ring_in[d..d + m_copy].copy_from_slice(&mbon_summary[..m_copy]);
        matvec(&w.b_ring_inh, &ring_in, cx_d, d + cfg.mbon_dim, &mut ring_gate);
        for j in 0..cx_d {
            ring_gate[j] = sigmoid(ring_gate[j] + w.b_ring_b[j]);
        }

        for sec in 0..sectors {
            let u_s = &u_phasor[sec * cx_d..(sec + 1) * cx_d];
            matvec(
                &w.b_delta7,
                u_s,
                cx_d,
                cx_d,
                &mut delta7_scores[sec * cx_d..(sec + 1) * cx_d],
            );
        }
        // Softmax along the 16-sector ring per channel to emulate Delta7 sinusoidal inhibition
        for j in 0..cx_d {
            let mut ring_col = [0.0f32; 16];
            for sec in 0..sectors {
                ring_col[sec] = delta7_scores[sec * cx_d + j];
            }
            softmax_inplace(&mut ring_col[..sectors]);
            for sec in 0..sectors {
                let u_val = u_phasor[sec * cx_d + j];
                let d7_inh = ring_col[sec] * u_val.abs();
                let ctx_inh = ring_gate[j] * u_val.abs() * 0.5;
                cx_phasor[sec * cx_d + j] = (u_val - d7_inh - ctx_inh).max(0.0);
            }
        }

        // Step D: Visual Centrifugal Inhibitory Feedback (71.8% I -> 64 squares) + Broadcaster update
        matvec(&w.b_cent_w, &broad_mean, 64, d, &mut cent_board_mask);
        for sq in 0..64 {
            cent_board_mask[sq] = sigmoid(cent_board_mask[sq] + w.b_cent_b[sq]);
        }
        matvec(&w.b_broad_to_sq, &broad_mean, d, d, &mut broad_proj);
        for sq in 0..64 {
            let gate = 1.0 - 0.718 * (1.0 - cent_board_mask[sq]); // Exact 71.8% inhibitory carving!
            let cur = &sq_state[sq * d..(sq + 1) * d];
            for j in 0..d {
                ctx_buf[j] = cur[j] * gate + 0.25 * broad_proj[j];
            }
            matvec(&w.b_sq_upd, &ctx_buf, d, d, &mut sq_tmp);
            for j in 0..d {
                sq_tmp[j] = cur[j] + 0.5 * sq_tmp[j].tanh();
            }
            layer_norm(&sq_tmp, &w.b_sq_ln_g, &w.b_sq_ln_b, &mut sq_ln);
            sq_state[sq * d..(sq + 1) * d].copy_from_slice(&sq_ln);
        }

        // Step E: Adaptive Compute Halting via Attractor Convergence (t >= 2)
        if adaptive_halt && tick >= 1 {
            let mut diff_sq = 0.0f32;
            let mut norm_sq = 1e-6f32;
            for i in 0..cx_phasor.len() {
                let df = cx_phasor[i] - prev_phasor[i];
                diff_sq += df * df;
                norm_sq += cx_phasor[i] * cx_phasor[i];
            }
            if (diff_sq / norm_sq).sqrt() < 0.06 {
                break;
            }
        }
    }

    // Pool final Central Complex phasor state across the 16 compass sectors
    let mut cx_pooled = vec![0.0f32; cx_d];
    for sec in 0..sectors {
        for j in 0..cx_d {
            cx_pooled[j] += cx_phasor[sec * cx_d + j] / sectors as f32;
        }
    }
    let mut global_vec = vec![0.0f32; d + cx_d];
    global_vec[..d].copy_from_slice(&broad_mean);
    global_vec[d..].copy_from_slice(&cx_pooled);

    // -------------------------------------------------------------------------
    // B5. K = 4 Orthogonal Creative Plan Bank + MBON-a'3 Novelty + LAL Commit
    // -------------------------------------------------------------------------
    let k_plans = cfg.num_creative_plans;
    let plan_in_dim = cx_d + d;
    let mut creative_plans = Vec::with_capacity(k_plans);
    let mut plan_weights = vec![0.0f32; k_plans];

    for k in 0..k_plans {
        let mut plan = vec![0.0f32; cx_d];
        let w_off = k * cx_d * plan_in_dim;
        let b_off = k * cx_d;
        matvec(
            &w.b_plan_bank[w_off..w_off + cx_d * plan_in_dim],
            &global_vec,
            cx_d,
            plan_in_dim,
            &mut plan,
        );
        let mut norm_sq = 1e-6f32;
        for j in 0..cx_d {
            plan[j] = (plan[j] + w.b_plan_b[b_off + j]).tanh();
            norm_sq += plan[j] * plan[j];
        }
        let inv_n = 1.0 / norm_sq.sqrt();
        for x in &mut plan {
            *x *= inv_n;
        }
        // Score each plan by base strength + LAL continuity + MBON-a'3 creative exploration bonus
        let lal_align = plasticity.map(|pl| pl.lal_alignment(&plan)).unwrap_or(0.0);
        // Plans 1..K receive a calibrated creativity lift when novelty_score is high
        let creative_lift = if k == 0 { 0.0 } else { 0.15 * novelty_score };
        plan_weights[k] = dot_f32(&plan, &cx_pooled) + 0.20 * lal_align + creative_lift;
        creative_plans.push(plan);
    }
    softmax_inplace(&mut plan_weights);

    let mut committed_goal = vec![0.0f32; cx_d];
    for k in 0..k_plans {
        for j in 0..cx_d {
            committed_goal[j] += plan_weights[k] * creative_plans[k][j];
        }
    }

    // -------------------------------------------------------------------------
    // B6. Readout Heads: Deep WDL, PFL2 Gain, Strategic Pressure, PFL3 Policy, Noduli, Seed
    // -------------------------------------------------------------------------
    let mut wdl_logits = [0.0f32; 3];
    for c in 0..3 {
        let row = &w.b_wdl_w[c * (d + cx_d)..(c + 1) * (d + cx_d)];
        wdl_logits[c] = dot_f32(row, &global_vec) + w.b_wdl_b[c];
    }
    let mut pos_probs = wdl_logits;
    softmax_inplace(&mut pos_probs);
    let deep_pos_cp = wdl_to_cp(pos_probs);
    let deep_cp = (sez_cp + deep_pos_cp).clamp(-2500.0, 2500.0);

    let sez_l = (sez_cp / 280.0).clamp(-5.0, 5.0);
    let mut wdl_probs = [wdl_logits[0] + sez_l, wdl_logits[1], wdl_logits[2] - sez_l];
    softmax_inplace(&mut wdl_probs);

    let pfl2_sharpness = sigmoid(dot_f32(&w.b_pfl2_w, &global_vec) + w.b_pfl2_b);

    let mut strategic_pressure = [0.0f32; 5];
    for p in 0..5 {
        let row = &w.b_press_w[p * (d + cx_d)..(p + 1) * (d + cx_d)];
        strategic_pressure[p] = (dot_f32(row, &global_vec) + w.b_press_b[p]).tanh();
    }

    // PFL3 (99% Contralateral) Bilinear Move Policy & Noduli Efference Copy
    let stm = pos.side_to_move;
    let mut q_sq = vec![0.0f32; 64 * cx_d];
    let mut k_sq = vec![0.0f32; 64 * cx_d];
    let mut opp_sq = vec![0.0f32; 64 * cx_d];
    for sq in 0..64 {
        let s = &sq_state[sq * d..(sq + 1) * d];
        matvec(&w.b_pfl3_q, s, cx_d, d, &mut q_sq[sq * cx_d..(sq + 1) * cx_d]);
        matvec(&w.b_pfl3_k, s, cx_d, d, &mut k_sq[sq * cx_d..(sq + 1) * cx_d]);
        matvec(&w.b_pfl3_opp, s, cx_d, d, &mut opp_sq[sq * cx_d..(sq + 1) * cx_d]);
    }

    let mut policy_moves = Vec::with_capacity(legal_moves.len());
    let mut logits_tmp = Vec::with_capacity(legal_moves.len());
    let inv_sqrt_cx = 1.0 / (cx_d as f32).sqrt();

    for &mv in legal_moves.as_slice() {
        let u = mv.from_sq().relative_to(stm).index();
        let v = mv.to_sq().relative_to(stm).index();
        let qu = &q_sq[u * cx_d..(u + 1) * cx_d];
        let kv = &k_sq[v * cx_d..(v + 1) * cx_d];
        let ov = &opp_sq[v * cx_d..(v + 1) * cx_d];

        let mut score = 0.0f32;
        let mut noduli_dot = 0.0f32;
        for j in 0..cx_d {
            let aligned_from = qu[j] * (1.0 + committed_goal[j]);
            let contra_to = kv[j] - 0.99 * ov[j]; // 99% contralateral opponent-defense comparison!
            score += aligned_from * contra_to;
            noduli_dot += w.b_noduli_w[j] * (aligned_from - contra_to);
        }
        let logit = score * inv_sqrt_cx;
        let expected_delta_cp = ((noduli_dot * inv_sqrt_cx + w.b_noduli_b).tanh()) * 250.0;
        logits_tmp.push(logit);
        policy_moves.push(PolicyMoveScore {
            mv,
            prob: 0.0,
            logit,
            expected_delta_cp,
        });
    }

    if !logits_tmp.is_empty() {
        softmax_inplace(&mut logits_tmp);
        for i in 0..policy_moves.len() {
            policy_moves[i].prob = logits_tmp[i];
        }
        policy_moves.sort_by(|a, b| b.prob.total_cmp(&a.prob));
    }

    // Stream B -> Stream A Top-Down Seed & Centrifugal KC Inhibitory Mask
    let rank = cfg.seed_rank;
    let (_, gamma_dim, _) = cfg.lobe_dims_per_hemi();
    let mut seed_latent = vec![0.0f32; rank];
    matvec(&w.b_seed_down, &global_vec, rank, d + cx_d, &mut seed_latent);
    for x in &mut seed_latent {
        *x = x.tanh();
    }
    let mut gamma_seed = vec![0.0f32; gamma_dim];
    matvec(&w.b_seed_to_gamma, &seed_latent, gamma_dim, rank, &mut gamma_seed);
    let mut centrifugal_kc_mask = vec![0.0f32; cfg.acc_dim];
    matvec(&w.b_seed_to_cent, &seed_latent, cfg.acc_dim, rank, &mut centrifugal_kc_mask);
    for x in &mut centrifugal_kc_mask {
        *x = sigmoid(*x);
    }

    StreamBOutput {
        deep_cp,
        wdl_probs,
        pfl2_sharpness,
        ticks_used,
        strategic_pressure,
        creative_plans,
        committed_goal,
        policy_moves,
        gamma_seed,
        centrifugal_kc_mask,
        centrifugal_board_mask: cent_board_mask,
    }
}
